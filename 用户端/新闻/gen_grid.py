def make_card(idx, cat, style, title, desc, img):
    mm = str(idx % 12 + 1).zfill(2)
    dd = str(idx % 28 + 1).zfill(2)
    return f'''                <div class="news-page-card {style}" data-category="{cat}" onclick="location.href='article-{idx}.html'">
                    <div class="card-image">
                        <img src="https://images.unsplash.com/photo-{img}?q=80&w=800" alt="{title}">
                    </div>
                    <div class="card-content">
                        <div class="card-date"><span>2026.{mm}.{dd}</span></div>
                        <h3 class="card-title">{title}</h3>
                        <p class="card-desc">{desc}</p>
                    </div>
                </div>'''

styles_map = {1:['card-white','card-blue','card-gray'], 2:['card-blue','card-white','card-gray'], 3:['card-gray','card-white','card-blue']}

lines = ['            <div class="news-page-grid">']
idx = 1
for cat, data in [(1,cat1),(2,cat2),(3,cat3)]:
    for i, (title,desc,img) in enumerate(data):
        style = styles_map[cat][i % 3]
        lines.append(make_card(idx, cat, style, title, desc, img))
        idx += 1
    lines.append('')
lines[-1] = '            </div>'

with open('news_grid_snippet.txt', 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))
print('done')
